#include "navigation.h"
#include "terminal_limits.h"
#include <assert.h>
#include <string.h>
int main(void) {
    pp_navigation_t nav = {0};
    assert(nav.screen == PP_SCREEN_HOME && !pp_navigation_menu(&nav));
    assert(pp_navigation_audio(&nav));
    pp_navigation_open(&nav, PP_SCREEN_MENU);
    assert(pp_navigation_count(&nav) == 5);
    assert(!pp_navigation_audio(&nav));
    assert(pp_navigation_selected(&nav) == PP_SELECT_TASKS);
    pp_navigation_move(&nav, -1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_HOME);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_TASKS);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_SOUND);
    pp_navigation_open(&nav, PP_SCREEN_SOUND);
    assert(pp_navigation_selected(&nav) == PP_SELECT_VOLUME);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_BRIGHTNESS);
    pp_navigation_open(&nav, PP_SCREEN_BRIGHTNESS);
    assert(pp_navigation_local(&nav) && !pp_navigation_menu(&nav));
    pp_navigation_back(&nav);
    assert(nav.screen == PP_SCREEN_SOUND && pp_navigation_selected(&nav) == PP_SELECT_BRIGHTNESS);
    pp_navigation_back(&nav);
    assert(nav.screen == PP_SCREEN_MENU && pp_navigation_selected(&nav) == PP_SELECT_SOUND);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_CONNECTIVITY);
    pp_navigation_open(&nav, PP_SCREEN_CONNECTIVITY);
    pp_navigation_open(&nav, PP_SCREEN_NETWORK);
    pp_navigation_back(&nav);
    assert(pp_navigation_selected(&nav) == PP_SELECT_NETWORK);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_RETRY);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_REPROVISION);
    assert(!strcmp(pp_navigation_detail(&nav), "开启热点，手机填写网络"));
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_MAINTENANCE);
    pp_navigation_open(&nav, PP_SCREEN_MAINTENANCE);
    assert(pp_navigation_selected(&nav) == PP_SELECT_RELOAD);
    assert(!strcmp(pp_navigation_detail(&nav), "从 PA 获取设备设置"));
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_REPAIR);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_FACTORY);
    pp_navigation_back(&nav);
    assert(nav.screen == PP_SCREEN_CONNECTIVITY);
    assert(pp_navigation_selected(&nav) == PP_SELECT_MAINTENANCE);
    pp_navigation_back(&nav);
    assert(nav.screen == PP_SCREEN_MENU && pp_navigation_selected(&nav) == PP_SELECT_CONNECTIVITY);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_POWER);
    pp_navigation_open(&nav, PP_SCREEN_POWER);
    assert(pp_navigation_selected(&nav) == PP_SELECT_KEEP_ONLINE);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_STANDBY_WIFI);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_SLEEP);
    pp_navigation_back(&nav);
    assert(pp_navigation_selected(&nav) == PP_SELECT_POWER);
    pp_navigation_move(&nav, 1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_HOME);
    pp_navigation_set_execution(&nav, true);
    assert(pp_navigation_count(&nav) == 6 && pp_navigation_selected(&nav) == PP_SELECT_HOME);
    pp_navigation_move(&nav, -1);
    assert(pp_navigation_selected(&nav) == PP_SELECT_CANCEL);
    assert(pp_navigation_ok_press(&nav, PP_ROUTE_LOCAL, 50, false));
    pp_navigation_set_execution(&nav, false);
    assert(!pp_navigation_ok_release(&nav, PP_ROUTE_LOCAL));
    assert(pp_navigation_selected(&nav) == PP_SELECT_HOME);
    pp_navigation_back(&nav);
    assert(nav.screen == PP_SCREEN_HOME);
    pp_navigation_open(&nav, PP_SCREEN_MENU);
    assert(pp_navigation_selected(&nav) == PP_SELECT_TASKS);
    pp_navigation_open(&nav, PP_SCREEN_TASK);
    pp_navigation_back(&nav);
    assert(nav.screen == PP_SCREEN_TASKS);
    pp_navigation_back(&nav);
    assert(nav.screen == PP_SCREEN_MENU);
    for (unsigned i = PP_SCREEN_MENU; i <= PP_SCREEN_MAINTENANCE; i++) {
        pp_navigation_open(&nav, i);
        assert(pp_navigation_local(&nav));
        assert(pp_navigation_count(&nav) <= 7);
        for (unsigned k = 0; k < pp_navigation_count(&nav); k++)
            assert(strlen(pp_navigation_label(&nav, k)) > 0);
    }
    pp_navigation_open(&nav, PP_SCREEN_HOME);
    assert(pp_navigation_route(&nav, false, true, false) == PP_ROUTE_SETUP);
    assert(pp_navigation_route(&nav, true, true, false) == PP_ROUTE_CONFIRM);
    assert(pp_navigation_route(&nav, false, false, true) == PP_ROUTE_REVIEW);
    assert(pp_navigation_route(&nav, false, false, false) == PP_ROUTE_SESSION);
    pp_navigation_open(&nav, PP_SCREEN_CONNECTIVITY);
    assert(pp_navigation_route(&nav, false, true, true) == PP_ROUTE_LOCAL);
    assert(pp_navigation_route(&nav, true, true, true) == PP_ROUTE_CONFIRM);
    pp_navigation_arrow_press(&nav, PP_ARROW_UP, 100, false, false);
    assert(pp_navigation_arrow_tick(&nav, 749, false) == PP_ARROW_NONE);
    assert(pp_navigation_arrow_release(&nav, PP_ARROW_UP));
    assert(!pp_navigation_arrow_release(&nav, PP_ARROW_UP));
    pp_navigation_arrow_press(&nav, PP_ARROW_UP, UINT32_MAX - 300, false, true);
    assert(pp_navigation_arrow_tick(&nav, 350, false) == PP_ARROW_UP);
    pp_navigation_open(&nav, PP_SCREEN_HOME);
    assert(pp_navigation_arrow_tick(&nav, 4000, false) == PP_ARROW_NONE);
    assert(!pp_navigation_standby_ready(&nav, 4000));
    assert(!pp_navigation_arrow_release(&nav, PP_ARROW_UP));
    pp_navigation_arrow_press(&nav, PP_ARROW_UP, 2000, false, true);
    assert(pp_navigation_arrow_release(&nav, PP_ARROW_UP));

    pp_navigation_open(&nav, PP_SCREEN_HISTORY);
    pp_navigation_arrow_press(&nav, PP_ARROW_DOWN, 3000, true, false);
    assert(pp_navigation_arrow_tick(&nav, 3649, true) == PP_ARROW_NONE);
    assert(pp_navigation_arrow_release(&nav, PP_ARROW_DOWN));
    pp_navigation_arrow_press(&nav, PP_ARROW_DOWN, 4000, true, false);
    assert(pp_navigation_arrow_tick(&nav, 4650, true) == PP_ARROW_DOWN);
    assert(pp_navigation_arrow_tick(&nav, 4800, true) == PP_ARROW_NONE);
    assert(!pp_navigation_arrow_release(&nav, PP_ARROW_DOWN));
    pp_navigation_arrow_press(&nav, PP_ARROW_DOWN, 5000, true, false);
    pp_navigation_open(&nav, PP_SCREEN_CHAT);
    assert(pp_navigation_arrow_tick(&nav, 5700, true) == PP_ARROW_NONE);
    assert(!pp_navigation_arrow_release(&nav, PP_ARROW_DOWN));
    pp_navigation_open(&nav, PP_SCREEN_MENU);
    pp_navigation_arrow_press(&nav, PP_ARROW_DOWN, 6000, false, false);
    assert(pp_navigation_arrow_tick(&nav, 6700, false) == PP_ARROW_NONE);
    assert(pp_navigation_arrow_release(&nav, PP_ARROW_DOWN));
    pp_navigation_open(&nav, PP_SCREEN_QUESTION);
    assert(pp_navigation_audio(&nav));
    pp_navigation_back(&nav);
    assert(nav.screen == PP_SCREEN_HOME);

    pp_navigation_arrow_press(&nav, PP_ARROW_UP, 7000, false, true);
    assert(pp_navigation_arrow_tick(&nav, 7000 + PP_ARROW_HOLD_MS, false) == PP_ARROW_NONE);
    assert(!pp_navigation_standby_ready(&nav, 7000 + PP_STANDBY_HOLD_MS - 1));
    assert(pp_navigation_standby_ready(&nav, 7000 + PP_STANDBY_HOLD_MS));
    assert(!pp_navigation_arrow_release(&nav, PP_ARROW_UP));
    assert(!pp_navigation_standby_ready(&nav, 11000));

    pp_navigation_arrow_press(&nav, PP_ARROW_UP, UINT32_MAX - 1000, false, true);
    assert(pp_navigation_standby_ready(&nav, 2000));
    pp_navigation_open(&nav, PP_SCREEN_CHAT);
    pp_navigation_open(&nav, PP_SCREEN_HOME);
    assert(!pp_navigation_standby_ready(&nav, 2100));
    assert(!pp_navigation_arrow_release(&nav, PP_ARROW_UP));

    assert(pp_navigation_ok_press(&nav, PP_ROUTE_SETUP, 100, false));
    assert(!pp_navigation_ok_wifi_tick(&nav, PP_ROUTE_SETUP, 400));
    assert(pp_navigation_ok_release(&nav, PP_ROUTE_SETUP));
    pp_navigation_open(&nav, PP_SCREEN_CONNECTIVITY);
    pp_navigation_ok_transition(&nav, 150);
    assert(!pp_navigation_ok_press(&nav, PP_ROUTE_LOCAL, 240, true));
    assert(!pp_navigation_ok_release(&nav, PP_ROUTE_LOCAL));
    assert(pp_navigation_ok_press(&nav, PP_ROUTE_LOCAL, 451, false));
    assert(pp_navigation_ok_release(&nav, PP_ROUTE_LOCAL));

    assert(pp_navigation_ok_press(&nav, PP_ROUTE_LOCAL, 500, true));
    pp_navigation_open(&nav, PP_SCREEN_NETWORK);
    pp_navigation_back(&nav);
    assert(!pp_navigation_ok_wifi_tick(&nav, PP_ROUTE_LOCAL, 800));
    assert(!pp_navigation_ok_release(&nav, PP_ROUTE_LOCAL));
    assert(pp_navigation_ok_press(&nav, PP_ROUTE_LOCAL, 850, true));
    assert(!pp_navigation_ok_wifi_tick(&nav, PP_ROUTE_CONFIRM, 1150));
    assert(!pp_navigation_ok_release(&nav, PP_ROUTE_CONFIRM));

    assert(pp_navigation_ok_press(&nav, PP_ROUTE_LOCAL, 1200, true));
    assert(!pp_navigation_ok_wifi_tick(&nav, PP_ROUTE_LOCAL, 1200 + PP_OK_HOLD_MS - 1));
    assert(pp_navigation_ok_release(&nav, PP_ROUTE_LOCAL));
    assert(pp_navigation_ok_press(&nav, PP_ROUTE_LOCAL, 1500, true));
    assert(pp_navigation_ok_wifi_tick(&nav, PP_ROUTE_LOCAL, 1500 + PP_OK_HOLD_MS));
    assert(!pp_navigation_ok_wifi_tick(&nav, PP_ROUTE_LOCAL, 1900));
    assert(!pp_navigation_ok_release(&nav, PP_ROUTE_LOCAL));
    return 0;
}
