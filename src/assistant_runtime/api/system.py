"""Host-bound OS facilities. No platform implementation or plugin registry lives here."""

from typing import Protocol, Any


class SystemIO(Protocol):
    @property
    def name(self) -> str: ...
    def directory(self, path) -> Any: ...
    def component(self, name: str) -> str: ...
    def supervised_command(self, timeout: float, args) -> list: ...
    def lock(self, stream, *, blocking: bool = True) -> None: ...
    def private(self, path, *, directory: bool = False) -> None: ...
    def sync_directory(self, path) -> None: ...
    def atomic_write(self, path, data: bytes, *, prefix: str = ".private-") -> None: ...
    async def spawn(self, *args, **kwargs) -> Any: ...
    async def stop_process(self, process, *, timeout: float = 5, graceful: bool = False) -> None: ...
    def signal_process(self, process, *, force: bool = False) -> None: ...
    def stop_signals(self, callback) -> None: ...
    async def terminal_input(self, *, secret: bool) -> str: ...


class _Binding:
    """Bound once by the package bootstrap, before application/plugin imports."""

    _provider: SystemIO | None = None

    def __getattr__(self, name):
        if self._provider is None:
            raise RuntimeError("Platform facilities are not bound")
        if name.startswith("_") or name not in SystemIO.__dict__:
            raise AttributeError(name)
        return getattr(self._provider, name)


system = _Binding()


def bind_system(provider: SystemIO):
    if system._provider is not None:
        raise RuntimeError("Platform facilities already bound")
    system._provider = provider
